#!/usr/bin/env python3
"""Expand Barik Roots dataset (apps/barik/data/surnames/surnames.txt) to 250-260 entries.

Reads the 105 seed entries (Batch 1 + Batch 2), validates every new curated Armenian
surname against data/words.json and www/audio/manifest.json (Anahit + Hayk voices),
and writes clean 12-column pipe-delimited rows without duplicate slugs.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
WORDS_PATH = os.path.join(APP, "data", "words.json")
MANIFEST_PATH = os.path.join(APP, "www", "audio", "manifest.json")
SURNAMES_PATH = os.path.join(APP, "data", "surnames", "surnames.txt")
LANGS = ("ru", "en", "fr", "es", "de", "pt")


def fnv(data: bytes, h: int) -> int:
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def aid(text: str) -> str:
    b = text.encode("utf-8")
    return f"{fnv(b, 0x811c9dc5):08x}{fnv(b, 0x050c5d1f):08x}"


def load_words():
    raw = json.load(open(WORDS_PATH, encoding="utf-8"))
    words = {}
    for topic in raw:
        lv = topic.get("lv", "A1")
        for item in topic.get("w", []):
            # [hy, ru, en, emo, fr, es, de, pt]
            hy = item[0]
            words[hy] = {
                "hy": hy,
                "lv": lv,
                "ru": item[1],
                "en": item[2],
                "fr": item[4],
                "es": item[5],
                "de": item[6],
                "pt": item[7],
            }
    return words


def load_manifest():
    man = json.load(open(MANIFEST_PATH, encoding="utf-8"))
    voices = man.get("voices", {})
    if not (voices.get("anahit", {}).get("count", 0) > 0 and voices.get("hayk", {}).get("count", 0) > 0):
        raise RuntimeError("audio/manifest.json missing anahit or hayk voice counts")
    return man


