def main():
    words = load_words()
    man = load_manifest()
    if len(words) == 0:
        raise RuntimeError("words.json empty")

    # Verify manifest covers dictionary size (both Anahit and Hayk)
    anahit_n = man["voices"]["anahit"]["count"]
    hayk_n = man["voices"]["hayk"]["count"]
    if anahit_n < len(words) or hayk_n < len(words):
        raise RuntimeError(f"Audio manifest incomplete: anahit={anahit_n}, hayk={hayk_n}, words={len(words)}")

    # Read existing seed lines (keep first 105 seed entries intact)
    seed_lines = [l.strip() for l in open(SURNAMES_PATH, encoding="utf-8") if l.strip()]
    seed_out = []
    seen = set()
    for l in seed_lines:
        cols = [c.strip() for c in l.split("|")]
        if len(cols) != 12:
            raise ValueError(f"Bad row in seed surnames.txt: {l[:80]}")
        sl = cols[0]
        if sl in seen:
            continue
        # Only preserve Batch 1 + Batch 2 up to first 105, re-applying expansion cleanly
        seen.add(sl)
        seed_out.append(" | ".join(cols))
        if len(seed_out) == 105:
            break

    added = 0
    for row in EXPANSION_ENTRIES:
        slug, hy, west, hy_root, rtr, cat, ru, en, fr, es, de, pt = row
        # Clean normalized slug if temporary suffix
        if slug == "vardapetyan_jr":
            slug = "vardazaryan"
        elif slug == "narek_ashughyan":
            slug = "narekyan"

        if slug in seen:
            continue
        if hy_root not in words:
            raise KeyError(f"Root '{hy_root}' for surname '{slug}' not found in words.json")

        # Verify audio hash deterministic ID + disk check if mp3 directory is present
        h = aid(hy_root)
        assert len(h) == 16
        for vdir in ("anahit", "hayk"):
            vpath = os.path.join(APP, "www", "audio", vdir)
            if os.path.isdir(vpath):
                mp3 = os.path.join(vpath, h[:2], f"{h}.mp3")
                if not os.path.isfile(mp3):
                    raise FileNotFoundError(f"Missing audio {mp3} for root '{hy_root}'")

        seen.add(slug)
        cols = [slug, hy, west, hy_root, rtr, cat, ru, en, fr, es, de, pt]
        if any("|" in c for c in cols):
            raise ValueError(f"Pipe char in cols for {slug}")
        seed_out.append(" | ".join(cols))
        added += 1

    with open(SURNAMES_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(seed_out) + "\n")

    cats = {}
    for l in seed_out:
        c = l.split("|")[5].strip()
        cats[c] = cats.get(c, 0) + 1
    print(f"Expanded surnames.txt: {len(seed_out)} total entries (+{added} verified against words.json + audio/manifest.json)")
    print("Categories:", cats)


if __name__ == "__main__":
    main()
