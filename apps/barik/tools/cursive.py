def path_of(pts):
    """Точки по ходу пера → путь SVG: центростремительный Catmull-Rom → кубические Безье,
    излом "c" рвёт сглаживание."""
    xy = [(float(p[0]), float(p[1])) for p in pts]
    cusp = [len(p) > 2 and p[2] == "c" for p in pts]
    d = f"M{xy[0][0]:g} {xy[0][1]:g}"
    if len(xy) == 2:
        return d + f"L{xy[1][0]:g} {xy[1][1]:g}"
    for i in range(len(xy) - 1):
        p1, p2 = xy[i], xy[i + 1]
        p0 = p1 if (i == 0 or cusp[i]) else xy[i - 1]
        p3 = p2 if (i + 2 >= len(xy) or cusp[i + 1]) else xy[i + 2]

        def tj(a, b):
            return max(math.dist(a, b) ** 0.5, 1e-4)
        t01, t12, t23 = tj(p0, p1), tj(p1, p2), tj(p2, p3)
        m1 = [(p2[k] - p1[k]) + t12 * ((p1[k] - p0[k]) / t01 - (p2[k] - p0[k]) / (t01 + t12)) for k in (0, 1)]
        m2 = [(p2[k] - p1[k]) + t12 * ((p3[k] - p2[k]) / t23 - (p3[k] - p1[k]) / (t12 + t23)) for k in (0, 1)]
        if p0 == p1:
            m1 = [p2[k] - p1[k] for k in (0, 1)]
        if p3 == p2:
            m2 = [p2[k] - p1[k] for k in (0, 1)]
        c1 = (p1[0] + m1[0] / 3, p1[1] + m1[1] / 3)
        c2 = (p2[0] - m2[0] / 3, p2[1] - m2[1] / 3)
        d += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:g} {p2[1]:g}"
    return d


XS = {"U": 1.3, "l": 1.42}   # ширина: штрихи рисовались узкими, пропись шире


def glyph(strokes, kind):
    k = XS[kind]
    strokes = [[(p[0] * k,) + tuple(p[1:]) for p in st] for st in strokes]
    xs = [p[0] for s in strokes for p in s]
    return {"x0": round(min(xs), 1), "w": round(max(xs) - min(xs), 1), "d": [path_of(s) for s in strokes]}


