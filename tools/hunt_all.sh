#!/bin/sh
# Прочёс всей базы кусками. Один длинный процесс не переживает ни
# перезапуск контейнера, ни отвал сети, поэтому охота идёт кусками по
# 400 лотов: hunt_checked дедуплицирует, и каждый следующий кусок
# продолжает с того места, где встал предыдущий.
#
# Замер 06.09.2026: 400 лотов ≈ 45 минут (потолок Discogs — 60 запросов
# в минуту на все методы сразу). 47 546 лотов ≈ 93 часа.
cd /home/user/Oncogen || exit 1
N="${1:-100}"          # сколько кусков сделать за один запуск
CHUNK="${2:-400}"
i=1
while [ "$i" -le "$N" ]; do
  echo "=== кусок $i/$N ($(date +%H:%M:%S)) ==="
  python3 -u tools/live_hunt.py --limit "$CHUNK" 2>&1 || echo "кусок $i упал, продолжаю"
  i=$((i+1))
done
